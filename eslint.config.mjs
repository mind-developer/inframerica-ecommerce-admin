import { defineConfig, globalIgnores } from 'eslint/config';
import nextVitals from 'eslint-config-next/core-web-vitals';
import nextTs from 'eslint-config-next/typescript';
import boundaries from 'eslint-plugin-boundaries';
import { builtinRules } from 'eslint/use-at-your-own-risk';

// The core max-lines rule under a second name, so one file size can warn and another can fail (ADR-0004).
const local = { rules: { 'max-lines-soft': builtinRules.get('max-lines') } };
const lineCount = { skipBlankLines: true, skipComments: true };

/** Architecture layers (ADR-0004). Order matters: the first matching pattern classifies a file. */
const elements = [
  { type: 'app', pattern: 'src/app' },
  { type: 'core', pattern: 'src/core' },
  { type: 'feature', pattern: 'src/features/*', capture: ['feature'] },
  { type: 'ui', pattern: 'src/components/ui' },
  { type: 'layout', pattern: 'src/components/layout' },
  { type: 'services', pattern: 'src/services' },
  { type: 'mocks', pattern: 'src/mocks' },
  { type: 'shared', pattern: 'src/(domain|hooks|utils|constants|types|styles|test)' },
];

/** Files directly in src/ aren't inside an element folder, so they're classified as files. */
const files = [
  { category: 'entry', pattern: 'src/proxy.ts' },
  // Tests and their helpers may reach any layer.
  { category: 'test', pattern: ['src/**/*.test.{ts,tsx}', 'src/test/**'] },
];

const ALL = ['app', 'core', 'feature', 'ui', 'layout', 'services', 'mocks', 'shared'];
/** A feature's public surface: `index.ts` (client-safe) and `server.ts` (server-only). */
const PUBLIC = '{index,server}.ts';

/** Who may import whom. Anything not listed is an error. */
const allow = (from, to) => ({
  from: { element: { type: from } },
  allow: { to: { element: { types: { anyOf: to } } } },
});
const policies = [
  { allow: { dependency: { relationship: { to: 'internal' } } } },
  { from: { file: { categories: 'entry' } }, allow: { to: { element: { types: { anyOf: ['core', 'shared'] } } } } },
  allow('app', ['core', 'feature', 'layout', 'ui', 'shared']),
  allow('core', ['feature', 'ui', 'services', 'shared']),
  allow('layout', ['feature', 'ui', 'shared']),
  allow('feature', ['ui', 'services', 'shared']),
  allow('ui', ['shared']),
  allow('services', ['mocks', 'shared']),
  allow('mocks', ['shared']),
  allow('shared', ['shared']),
  { from: { file: { categories: 'test' } }, allow: { to: { element: { types: { anyOf: ALL } } } } },
  // Features talk to each other only through the other feature's public files.
  { from: { element: { type: 'feature' } }, allow: { to: { element: { type: 'feature', fileInternalPath: PUBLIC } } } },
  // Routes, layouts and wiring also go through a feature's public files, never its internals.
  {
    from: { element: { types: { anyOf: ['app', 'layout', 'core'] } } },
    disallow: { to: { element: { type: 'feature', fileInternalPath: `!${PUBLIC}` } } },
  },
];

export default defineConfig([
  ...nextVitals,
  ...nextTs,
  globalIgnores(['.next/**', 'out/**', 'build/**', 'coverage/**', 'next-env.d.ts']),
  {
    files: ['**/*.{ts,tsx}'],
    plugins: { local },
    rules: {
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/no-unused-vars': ['error', { ignoreRestSiblings: true, argsIgnorePattern: '^_' }],
      // File size (ADR-0004): aim for ≤ 150 lines, never above 250. Split instead of growing.
      'local/max-lines-soft': ['warn', { max: 150, ...lineCount }],
      'max-lines': ['error', { max: 250, ...lineCount }],
      'max-lines-per-function': ['warn', { max: 80, ...lineCount, IIFEs: true }],
      // Components go through the services/ layer, never fetch directly.
      'no-restricted-globals': ['error', { name: 'fetch', message: 'Use a service in src/services/.' }],
    },
  },
  {
    files: ['src/**/*.{ts,tsx}'],
    plugins: { boundaries },
    settings: {
      'boundaries/elements': elements,
      'boundaries/files': files,
      'import/resolver': { typescript: { alwaysTryTypes: true } },
    },
    rules: {
      'boundaries/dependencies': ['error', { default: 'disallow', policies }],
      'boundaries/no-unknown-files': 'error',
    },
  },
  {
    files: ['src/services/**/*.ts'],
    rules: { 'no-restricted-globals': 'off' },
  },
  {
    // Data tables and tests may be long; logic files may not.
    files: ['src/mocks/**', '**/*.test.{ts,tsx}', 'src/constants/**'],
    rules: { 'local/max-lines-soft': 'off', 'max-lines-per-function': 'off', 'max-lines': 'off' },
  },
  {
    // Generated by the shadcn CLI (charts); kept as generated so it can be re-synced.
    files: ['src/components/ui/chart.tsx'],
    rules: { 'local/max-lines-soft': 'off', 'max-lines-per-function': 'off', 'max-lines': 'off' },
  },
]);
